// Derives a whole app theme (Material 3 colours + a heading/body font pair) from design/seed.
// Outputs are listed in design/theme.config.json; paths there are relative to the project root.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { argbFromHex, Hct, MaterialDynamicColors, SchemeTonalSpot } from '@material/material-color-utilities';

const designDir = dirname(fileURLToPath(import.meta.url));
const root = join(designDir, '..');

const seed = readFileSync(join(designDir, 'seed'), 'utf8').trim();
if (!/^[0-9a-f]{64}$/.test(seed)) {
  throw new Error('design/seed must be exactly 64 lowercase hex characters');
}
const config = JSON.parse(readFileSync(join(designDir, 'theme.config.json'), 'utf8'));
if (!config.compose && !config.swiftui && !config.css) {
  throw new Error('design/theme.config.json must configure at least one of: compose, swiftui, css');
}

const seedColor = `#${seed.slice(0, 6)}`;

// Order matters: the seed indexes into these lists, so reordering changes every existing design.
const headingFonts = [
  'Lora', 'Merriweather', 'Playfair Display', 'Source Serif 4',
  'Crimson Pro', 'Fraunces', 'EB Garamond', 'Newsreader',
];
const bodyFonts = [
  'Inter', 'Source Sans 3', 'Nunito Sans', 'Work Sans',
  'IBM Plex Sans', 'DM Sans', 'Figtree', 'Manrope',
];
const headingFont = headingFonts[parseInt(seed.slice(6, 8), 16) % headingFonts.length];
const bodyFont = bodyFonts[parseInt(seed.slice(8, 10), 16) % bodyFonts.length];

const colorRoles = [
  'primary', 'onPrimary', 'primaryContainer', 'onPrimaryContainer', 'inversePrimary',
  'secondary', 'onSecondary', 'secondaryContainer', 'onSecondaryContainer',
  'tertiary', 'onTertiary', 'tertiaryContainer', 'onTertiaryContainer',
  'background', 'onBackground', 'surface', 'onSurface', 'surfaceVariant', 'onSurfaceVariant',
  'surfaceTint', 'inverseSurface', 'inverseOnSurface',
  'error', 'onError', 'errorContainer', 'onErrorContainer',
  'outline', 'outlineVariant', 'scrim',
  'surfaceBright', 'surfaceDim', 'surfaceContainerLowest', 'surfaceContainerLow',
  'surfaceContainer', 'surfaceContainerHigh', 'surfaceContainerHighest',
];

// role -> 6-digit uppercase RGB hex (all scheme colours are opaque).
function scheme(isDark) {
  const s = new SchemeTonalSpot(Hct.fromInt(argbFromHex(seedColor)), isDark, 0);
  return Object.fromEntries(colorRoles.map((role) => [
    role,
    (MaterialDynamicColors[role].getArgb(s) >>> 0).toString(16).toUpperCase().padStart(8, '0').slice(2),
  ]));
}
const light = scheme(false);
const dark = scheme(true);

const header = (comment) => `${comment} Generated by design/generate-theme.mjs from design/seed. Do not edit by hand.`;

function write(relativePath, contents) {
  const path = join(root, relativePath);
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, contents);
  console.log(`-> ${relativePath}`);
}

if (config.compose) {
  const args = (colors) => colorRoles.map((r) => `    ${r} = Color(0xFF${colors[r]}),`).join('\n');
  write(config.compose.path, `${header('//')}
package ${config.compose.package}

import androidx.compose.material3.darkColorScheme
import androidx.compose.material3.lightColorScheme
import androidx.compose.ui.graphics.Color

val LightColorScheme = lightColorScheme(
${args(light)}
)

val DarkColorScheme = darkColorScheme(
${args(dark)}
)
`);
}

if (config.swiftui) {
  const lets = colorRoles.map((r) => `    static let ${r} = dynamic(light: 0x${light[r]}, dark: 0x${dark[r]})`).join('\n');
  write(config.swiftui.path, `${header('//')}
import SwiftUI
import UIKit

enum ThemeColor {
${lets}

    private static func dynamic(light: UInt32, dark: UInt32) -> Color {
        Color(UIColor { traits in rgb(traits.userInterfaceStyle == .dark ? dark : light) })
    }

    private static func rgb(_ hex: UInt32) -> UIColor {
        UIColor(
            red: CGFloat((hex >> 16) & 0xFF) / 255,
            green: CGFloat((hex >> 8) & 0xFF) / 255,
            blue: CGFloat(hex & 0xFF) / 255,
            alpha: 1
        )
    }
}

// Family names for Font.custom(_:size:). The TTFs must be bundled and listed under UIAppFonts in Info.plist.
enum ThemeFont {
    static let heading = "${headingFont}"
    static let body = "${bodyFont}"
}
`);
}

if (config.css) {
  const kebab = (role) => role.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);
  const vars = (colors) => colorRoles.map((r) => `  --color-${kebab(r)}: #${colors[r]};`).join('\n');
  write(config.css.path, `${header('/*')} */
:root {
  color-scheme: light dark;
  --font-heading: '${headingFont}', serif;
  --font-body: '${bodyFont}', sans-serif;
${vars(light)}
}

@media (prefers-color-scheme: dark) {
  :root {
${vars(dark).replaceAll('\n', '\n  ').replace(/^/, '  ')}
  }
}
`);
}

// M3's type scale only uses regular (400) and medium (500).
const fontWeights = { regular: 400, medium: 500 };

async function downloadFont(family, role) {
  const weights = Object.values(fontWeights).join(';');
  const cssUrl = `https://fonts.googleapis.com/css2?family=${family.replaceAll(' ', '+')}:wght@${weights}`;
  // A non-browser user agent makes Google Fonts serve static TTF files.
  const css = await (await fetch(cssUrl, { headers: { 'User-Agent': 'seed-theme-generator' } })).text();
  const files = {};
  for (const [name, weight] of Object.entries(fontWeights)) {
    const block = css.split('@font-face').find((b) => b.includes(`font-weight: ${weight};`));
    const url = block?.match(/url\((https:[^)]+\.ttf)\)/)?.[1];
    if (!url) throw new Error(`No ${weight} TTF for ${family}`);
    files[`${role}_${name}.ttf`] = Buffer.from(await (await fetch(url)).arrayBuffer());
  }
  // The SIL Open Font License requires its text to ship with the font files.
  const licenseUrl = `https://raw.githubusercontent.com/google/fonts/main/ofl/${family.replaceAll(' ', '').toLowerCase()}/OFL.txt`;
  const license = await fetch(licenseUrl);
  if (!license.ok) throw new Error(`No OFL license found for ${family}`);
  const licenseText = await license.text();

  for (const dir of config.fonts.dirs) {
    for (const [file, bytes] of Object.entries(files)) write(join(dir, file), bytes);
  }
  write(join(config.fonts.licenseDir, `${role}-OFL.txt`), licenseText);
}

console.log(`Seed colour ${seedColor}; heading font ${headingFont}; body font ${bodyFont}`);
if (config.fonts) {
  await downloadFont(headingFont, 'heading');
  await downloadFont(bodyFont, 'body');
}
